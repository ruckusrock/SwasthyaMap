function serviceMatches(listing, ...terms) {
  const value = `${listing.services?.en || ""} ${listing.driveType || ""}`.toLowerCase();
  return terms.some(term => value.includes(term));
}

function isOpenNow(listing) {
  return listing.openNow === true || listing.openNow === "true" || listing.openNow === 1;
}

